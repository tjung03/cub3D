#include "utils_bonus.h"

int		ft_atoi(char *line, int *i)
{
	int		num;

	num = 0;
	skip_space(line, i);
	while (line[*i] >= '0' && line[*i] <= '9')
	{
		num = num * 10 + (line[*i] - 48);
		(*i)++;
	}
	return (num);
}
